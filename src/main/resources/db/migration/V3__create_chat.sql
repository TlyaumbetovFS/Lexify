create table rooms (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references users(id) on delete cascade,
    name varchar(100) not null,
    description varchar(1000)
);

create index rooms_owner_id_idx on rooms(owner_id);

create table room_moderators (
    room_id bigint not null references rooms(id) on delete cascade,
    user_id bigint not null references users(id) on delete cascade,
    primary key (room_id, user_id)
);

create index room_moderators_user_id_idx on room_moderators(user_id);

create table messages (
    id bigint generated by default as identity primary key,
    room_id bigint not null references rooms(id) on delete cascade,
    author_id bigint not null references users(id) on delete cascade,
    text varchar(2000) not null,
    created_at timestamptz not null
);

create index messages_room_id_id_idx on messages(room_id, id desc);
create index messages_author_id_idx on messages(author_id);
