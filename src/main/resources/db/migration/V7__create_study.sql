create table study_cards (
    id bigint generated by default as identity primary key,
    word_id bigint not null references words(id) on delete cascade,
    direction varchar(2) not null check (direction in ('en', 'ru')),
    card_state text not null,
    due timestamptz not null,
    reviews integer not null default 0,
    unique (word_id, direction)
);
create index study_cards_due_idx on study_cards(due);
create table study_reviews (
    id bigint generated by default as identity primary key,
    card_id bigint not null references study_cards(id) on delete cascade,
    rating integer not null check (rating between 1 and 4),
    reviewed_at timestamptz not null,
    next_due timestamptz not null
);
create index study_reviews_card_idx on study_reviews(card_id);
